# -*- coding: utf-8 -*-
"""Odoo-side tests for the guided work-order flow (manufacturing)."""
from odoo.tests import TransactionCase, tagged
from odoo import Command


@tagged("post_install", "-at_install")
class TestMfgGuide(TransactionCase):
    def setUp(self):
        super().setUp()
        self.service = self.env["mmux.service"]
        self.product = self.env["product.product"].create({
            "name": "MMUX Guided FG", "is_storable": True,
            "barcode": "MMUX-FG1",
        })
        self.component = self.env["product.product"].create({
            "name": "MMUX Guided Component", "is_storable": True,
        })
        self.bom = self.env["mrp.bom"].create({
            "product_tmpl_id": self.product.product_tmpl_id.id,
            "product_qty": 1,
            "type": "normal",
            "bom_line_ids": [Command.create({
                "product_id": self.component.id,
                "product_qty": 1,
            })],
        })

    def _make_workorder(self):
        mo = self.env["mrp.production"].create({
            "product_id": self.product.id,
            "product_qty": 10,
            "bom_id": self.bom.id,
        })
        mo.action_confirm()
        mo.action_assign()
        wo = mo.workorder_ids[:1]
        if wo:
            wo.state = "ready"
        return mo, wo

    def test_mfg_guide_flow_listed(self):
        ids = [f["flow_id"] for f in self.service.guide_flows()]
        self.assertIn("mfg_guided_workorder", ids)

    def test_guided_workorder_loop(self):
        """引导闭环：到工位 → 扫工单 → 口述报工（L2 走守卫）→ 收尾。"""
        mo, wo = self._make_workorder()
        if not wo:
            self.skipTest("no workorder generated by this BOM config")
        view = self.service.guide_start("mfg_guided_workorder",
                                        {"workorder_id": wo.id})
        self.assertFalse(view["finished"])
        key = view["guide_key"]

        # s1: goto (skippable confirm)
        self.assertTrue(view["current"]["step_id"].startswith("goto_wo_"))
        view = self.service.guide_advance(key, view["current"]["step_id"])

        # s2: scan (capability-backed query, advances)
        self.assertTrue(view["current"]["step_id"].startswith("scan_wo_"))
        view = self.service.guide_advance(key, view["current"]["step_id"],
                                          {"barcode": "MMUX-FG1"})

        # s3: report (L2 -> pauses for confirmation)
        self.assertTrue(view["current"]["step_id"].startswith("report_wo_"))
        view = self.service.guide_advance(
            key, view["current"]["step_id"],
            {"qty_production": 8, "qty_scrapped": 1})
        self.assertEqual(view["state"], "awaiting_confirmation")
        cur = view["step"]["step_id"]
        view = self.service.guide_advance(
            key, cur, {"qty_production": 8, "qty_scrapped": 1, "confirmed": True})
        self.assertEqual(view.get("last_exec"), "success")

        # s4: close-out (skippable)
        self.assertTrue(view["current"]["step_id"].startswith("next_check_"))
        view = self.service.guide_advance(key, view["current"]["step_id"])
        self.assertTrue(view["finished"])

    def test_cannot_report_while_before_scan(self):
        mo, wo = self._make_workorder()
        if not wo:
            self.skipTest("no workorder generated by this BOM config")
        view = self.service.guide_start("mfg_guided_workorder",
                                        {"workorder_id": wo.id})
        res = self.service.guide_advance(
            view["guide_key"], f"report_wo_{wo.id}", {"qty_production": 1})
        self.assertIn("error", res)
