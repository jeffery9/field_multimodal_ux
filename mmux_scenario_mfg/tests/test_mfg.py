"""Manufacturing BDD tests (PRD §10.2 制造验收)."""
from odoo.tests import TransactionCase, tagged
from odoo import Command


@tagged("post_install", "-at_install")
class TestManufacturingScenario(TransactionCase):
    def setUp(self):
        super().setUp()
        self.service = self.env["mmux.service"]
        self.product = self.env["product.product"].create({
            "name": "MMUX Finished Good",
            "is_storable": True,
        })
        self.component = self.env["product.product"].create({
            "name": "MMUX Component",
            "is_storable": True,
        })
        self.bom = self.env["mrp.bom"].create({
            "product_tmpl_id": self.product.product_tmpl_id.id,
            "product_qty": 1,
            "type": "normal",
            "bom_line_ids": [Command.create({
                "product_id": self.component.id,
                "product_qty": 1,
            })],
        })

    def _make_mo(self):
        mo = self.env["mrp.production"].create({
            "product_id": self.product.id,
            "product_qty": 10,
            "bom_id": self.bom.id,
        })
        mo.action_confirm()
        return mo

    def test_query_next_operation(self):
        mo = self._make_mo()
        res = self.service.execute_capability(
            "mo_query_next_operation", {}, record_id=mo.id, idem_key="mmux:mfg-q1")
        self.assertEqual(res["status"], "success")

    def test_voice_report_production_flow(self):
        """口述「完成120件，3件不合格」→ LLM 识别 → 确认 → 原生 record_production。"""
        Param = self.env["ir.config_parameter"].sudo()
        Param.set_param("mmux.llm.provider", "mock")
        Param.set_param("mmux.llm.mock_response", {
            "normalized_text": "report 120 units produced, 3 scrapped",
            "capability_id": "wo_report_production",
            "params": {"qty_production": 120, "qty_scrapped": 3},
            "missing": [], "ambiguous": [], "confidence": 0.9})
        intent = self.service.parse_intent("本工序完成120件，其中3件不合格")
        self.assertEqual(intent["capability_id"], "wo_report_production")
        self.assertEqual(intent["params"]["qty_production"], 120)
        self.assertEqual(intent["params"]["qty_scrapped"], 3)
        mo = self._make_mo()
        mo.action_confirm()
        wo = mo.workorder_ids[:1]
        if not wo:
            self.skipTest("no workorder generated by this BOM config")
        wo.state = "ready"
        res = self.service.execute_capability(
            "wo_report_production",
            {"qty_production": 120, "qty_scrapped": 3},
            record_id=wo.id, idem_key="mmux:mfg-r1")
        self.assertEqual(res["status"], "awaiting_confirmation")
        res = self.service.execute_capability(
            "wo_report_production",
            {"qty_production": 120, "qty_scrapped": 3},
            record_id=wo.id, idem_key="mmux:mfg-r1", confirmed=True)
        self.assertEqual(res["status"], "success")

    def test_report_rejected_on_cancelled_workorder(self):
        """Acceptance: 非法状态变更被拒绝（原生状态约束）。"""
        mo = self._make_mo()
        wo = mo.workorder_ids[:1]
        if not wo:
            self.skipTest("no workorder generated by this BOM config")
        wo.state = "cancelled"
        res = self.service.execute_capability(
            "wo_report_production", {"qty_production": 5},
            record_id=wo.id, idem_key="mmux:mfg-r2", confirmed=True)
        self.assertEqual(res["status"], "failed")

    def test_equipment_failure_creates_draft_request(self):
        equipment = self.env["maintenance.equipment"].create({"name": "MMUX Mill"})
        res = self.service.execute_capability(
            "equipment_report_failure", {"description": "主轴异响，需要检修"},
            record_id=equipment.id, idem_key="mmux:mfg-f1")
        self.assertEqual(res["status"], "success")
        req = self.env["maintenance.request"].browse(res["result"]["request_id"])
        self.assertIn("主轴异响", req.name)
